"""Download the raw quote datasets into data/raw/<source_name>/.

Files under data/raw are written once and never modified afterwards: re-running
skips any source that has already been downloaded. Provenance captured at
download time is kept in data/raw/<source_name>/download.json, and
data/raw/SOURCES.md is rendered from it.

Usage: python scripts/data/fetch_raw.py
"""

from __future__ import annotations

import json
import shutil
import sys
from datetime import date
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RAW_DIR = ROOT / "data" / "raw"
META_FILE = "download.json"

HF_REPO = "Abirate/english_quotes"
HF_FILE = "quotes.jsonl"
KAGGLE_SLUG = "manann/quotes-500k"
KAGGLE_FILE = "quotes.csv"

# Columns each raw file must have; anything else means the source changed and
# needs a human look before it goes into the corpus.
EXPECTED_COLUMNS = {
    "english_quotes": ["quote", "author", "tags"],
    "quotes_500k": ["quote", "author", "category"],
}


def read_raw(source: str, path: Path) -> pd.DataFrame:
    """Read a raw source file. Shared with build_corpus.py so both see the same rows."""
    if source == "english_quotes":
        return pd.read_json(path / HF_FILE, lines=True)
    if source == "quotes_500k":
        return pd.read_csv(path / KAGGLE_FILE, dtype=str, keep_default_na=False)
    raise ValueError(f"unknown source {source!r}")


def fetch_english_quotes(dest: Path) -> dict:
    from huggingface_hub import HfApi, hf_hub_download

    info = HfApi().dataset_info(HF_REPO)
    cached = hf_hub_download(HF_REPO, HF_FILE, repo_type="dataset", revision=info.sha)
    shutil.copyfile(cached, dest / HF_FILE)
    license_tags = [t.split(":", 1)[1] for t in info.tags if t.startswith("license:")]
    return {
        "url": f"https://huggingface.co/datasets/{HF_REPO}",
        "identifier": f"{HF_REPO} @ {info.sha}",
        "license": ", ".join(license_tags)
        or "Not declared on the dataset card (scraped from goodreads.com/quotes)",
        "files": [HF_FILE],
    }


def fetch_quotes_500k(dest: Path) -> dict:
    from kaggle.api.kaggle_api_extended import KaggleApi

    api = KaggleApi()
    api.authenticate()
    owner, name = KAGGLE_SLUG.split("/")
    [meta] = [d for d in api.dataset_list(search=name, user=owner) if d.ref == KAGGLE_SLUG]
    api.dataset_download_file(KAGGLE_SLUG, KAGGLE_FILE, path=str(dest), quiet=False, unzip=True)
    if not (dest / KAGGLE_FILE).exists():
        raise SystemExit(f"Kaggle download did not produce {dest / KAGGLE_FILE}")
    return {
        "url": f"https://www.kaggle.com/datasets/{KAGGLE_SLUG}",
        "identifier": f"{KAGGLE_SLUG} (version {meta.current_version_number})",
        "license": f"{meta.license_name} (Kaggle). Upstream README "
        "(github.com/ShivaliGoel/Quotes-500K): made public 'for educational and "
        "research purposes'; cite Goel et al., ECIR 2018",
        "files": [KAGGLE_FILE],
    }


FETCHERS = {
    "english_quotes": fetch_english_quotes,
    "quotes_500k": fetch_quotes_500k,
}


def ensure_downloaded(source: str) -> dict:
    dest = RAW_DIR / source
    meta_path = dest / META_FILE
    if meta_path.exists():
        print(f"[{source}] already downloaded, skipping")
        return json.loads(meta_path.read_text())
    if dest.exists():
        raise SystemExit(f"{dest} exists but has no {META_FILE}; refusing to touch it")
    # Download into a scratch dir and rename at the end, so an interrupted run
    # never leaves a half-written source behind.
    partial = RAW_DIR / f".{source}.partial"
    shutil.rmtree(partial, ignore_errors=True)
    partial.mkdir(parents=True)
    print(f"[{source}] downloading")
    meta = FETCHERS[source](partial)
    meta["download_date"] = date.today().isoformat()
    (partial / META_FILE).write_text(json.dumps(meta, indent=2) + "\n")
    partial.rename(dest)
    return meta


def render_sources(entries: list[tuple[str, dict, pd.DataFrame]]) -> str:
    lines = ["# Raw data sources", "", "Generated by `scripts/data/fetch_raw.py`. Files here are never modified.", ""]
    for source, meta, df in entries:
        lines += [
            f"## {source}",
            "",
            f"- URL: {meta['url']}",
            f"- Identifier: `{meta['identifier']}`",
            f"- Download date: {meta['download_date']}",
            f"- License: {meta['license']}",
            f"- Files: {', '.join(meta['files'])}",
            f"- Rows: {len(df):,}",
            f"- Columns: {', '.join(df.columns)}",
            "",
        ]
    return "\n".join(lines)


def main() -> None:
    entries = []
    for source, expected in EXPECTED_COLUMNS.items():
        meta = ensure_downloaded(source)
        df = read_raw(source, RAW_DIR / source)
        print(f"[{source}] {len(df):,} rows, columns {list(df.columns)}")
        if list(df.columns) != expected:
            sys.exit(f"[{source}] expected columns {expected}, got {list(df.columns)}")
        entries.append((source, meta, df))
    (RAW_DIR / "SOURCES.md").write_text(render_sources(entries))
    print(f"wrote {RAW_DIR / 'SOURCES.md'}")


if __name__ == "__main__":
    main()
